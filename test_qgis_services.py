from unittest import TestCase

import pytest

# The same tests run on the QGIS Server behind the geoportal proxy (with the GeoMapFish plugin)
# and on a bare QGIS Server, to identify what the plugin changes, see the targets in conftest.py.
DEMO_COLLECTIONS = [
    "demo01_edit_point",
    "demo02_edit_line",
    "demo03_edit_polygon",
    "demo04_edit_multiline",
    "demo05_edit_multipolygon"
]
CRS_2056 = "http://www.opengis.net/def/crs/EPSG/0/2056"

# Test geometries in EPSG:2056, one per collection geometry type
_RING = [
    [2558000.0, 1210900.0],
    [2558100.0, 1210900.0],
    [2558100.0, 1211000.0],
    [2558000.0, 1211000.0],
    [2558000.0, 1210900.0],
]
_LINE = [[2558000.0, 1210900.0], [2558100.0, 1211000.0]]
DEMO_GEOMETRIES = {
    "demo01_edit_point": {"type": "Point", "coordinates": [2558050.0, 1210950.0]},
    "demo02_edit_line": {"type": "LineString", "coordinates": _LINE},
    "demo03_edit_polygon": {"type": "Polygon", "coordinates": [_RING]},
    "demo04_edit_multiline": {"type": "MultiLineString", "coordinates": [_LINE]},
    "demo05_edit_multipolygon": {"type": "MultiPolygon", "coordinates": [[_RING]]},
}


class QGISServicesTests:
    """
    Tests on OGC API Features, run on each QGIS Server by the subclasses below
    """

    @pytest.fixture(autouse=True, scope="function")
    def _setUp(self, init_config):
        self.client = init_config.get("client")
        self.base_url = init_config.get("base_url")
        self.ogcapi_url = self.base_url + init_config.get("ogcapi_path")

    def _items_url(self, collection, item_id=None):
        url = "{}/collections/{}/items".format(self.ogcapi_url, collection)
        if item_id is not None:
            url += "/{}".format(item_id)
        return url

    def test_collections(self):
        """
        Tests OGC API Features collections list contains the demo collections
        """
        response = self.client.get(
            self.ogcapi_url + "/collections", params={"f": "json"}, verify=False
        )
        self.assertEqual(response.status_code, 200)
        collection_ids = [c["id"] for c in response.json()["collections"]]
        for collection in DEMO_COLLECTIONS:
            self.assertIn(collection, collection_ids)

    def test_links_base_url(self):
        """
        Tests links generated by QGIS Server point back to the geoportal proxy
        """
        response = self.client.get(
            self.ogcapi_url + "/collections", params={"f": "json"}, verify=False
        )
        self.assertEqual(response.status_code, 200)
        for link in response.json()["links"]:
            self.assertTrue(
                link["href"].startswith(self.ogcapi_url),
                "{} does not start with {}".format(link["href"], self.ogcapi_url),
            )

    def test_schema(self):
        """
        Tests schema (OGC API Features part 5) exposes required, read only,
        enum, code list, pattern, ordering and foreign key information
        """
        response = self.client.get(
            "{}/collections/{}/schema.json".format(
                self.ogcapi_url, "demo01_edit_point"
            ),
            verify=False,
        )
        self.assertEqual(response.status_code, 200)
        schema = response.json()
        properties = schema["properties"]
        self.assertCountEqual(schema["required"], ["details", "geometry"])
        # Read only attributes
        self.assertTrue(properties["id"]["readOnly"])
        self.assertEqual(properties["id"]["x-ogc-role"], "id")
        # PostgreSQL enum
        self.assertCountEqual(
            properties["state"]["enum"], ["OPEN", "CLOSED", "UNKNOWN"]
        )
        # REGEX constraint and length
        self.assertEqual(properties["code"]["pattern"], "^[A-Z]{3}$")
        self.assertEqual(properties["code"]["maxLength"], 3)
        # Attributes order from the Drag & Drop Designer
        self.assertEqual(properties["id"]["x-ogc-propertySeq"], 0)
        self.assertEqual(properties["parent_ref"]["x-ogc-propertySeq"], 1)
        self.assertEqual(properties["details"]["x-ogc-propertySeq"], 2)
        # Foreign key to another collection
        self.assertEqual(properties["parent_ref"]["x-ogc-role"], "reference")
        self.assertEqual(
            properties["parent_ref"]["x-ogc-collectionId"], "demo06_edit_parent"
        )
        self.assertEqual(properties["geometry"]["format"], "geometry-point")
        self.assertEqual(properties["geometry"]["x-ogc-role"], "primary-geometry")

    def test_items(self):
        """
        Tests items can be read, in CRS84 by default and in EPSG:2056 on demand
        """
        response = self.client.get(
            self._items_url("demo01_edit_point"), params={"f": "json"}, verify=False
        )
        self.assertEqual(response.status_code, 200)
        features = response.json()["features"]
        self.assertTrue(len(features) > 0)
        x, y = features[0]["geometry"]["coordinates"]
        self.assertTrue(-180 <= x <= 180 and -90 <= y <= 90)

        response = self.client.get(
            self._items_url("demo01_edit_point"),
            params={"f": "json", "crs": CRS_2056},
            verify=False,
        )
        self.assertEqual(response.status_code, 200)
        x, y = response.json()["features"][0]["geometry"]["coordinates"]
        self.assertTrue(2400000 < x < 2900000 and 1000000 < y < 1400000)

    def test_crud(self):
        """
        Tests create, read, update and delete of a feature on every demo collection
        """
        for collection in DEMO_COLLECTIONS:
            with self.subTest(collection=collection):
                self._check_crud(collection)

    def _check_crud(self, collection):
        feature = {
            "type": "Feature",
            "properties": {"details": "Created by test", "state": "OPEN"},
            "geometry": DEMO_GEOMETRIES[collection],
        }

        # Create
        response = self.client.post(
            self._items_url(collection),
            params={"crs": CRS_2056},
            json=feature,
            headers={"Content-Type": "application/geo+json"},
            verify=False,
        )
        self.assertEqual(response.status_code, 201, response.text)
        # Don't follow the Location header, its base URL may not be the proxy one
        item_id = response.headers["Location"].rstrip("/").split("/")[-1]
        item_url = self._items_url(collection, item_id)

        try:
            # Read
            response = self.client.get(
                item_url, params={"f": "json", "crs": CRS_2056}, verify=False
            )
            self.assertEqual(response.status_code, 200)
            created = response.json()
            self.assertEqual(created["properties"]["details"], "Created by test")
            self.assertEqual(created["properties"]["state"], "OPEN")
            self.assertEqual(created["geometry"]["type"], feature["geometry"]["type"])

            # Update
            feature["properties"] = {"details": "Updated by test", "state": "CLOSED"}
            response = self.client.put(
                item_url,
                params={"crs": CRS_2056},
                json=feature,
                headers={"Content-Type": "application/geo+json"},
                verify=False,
            )
            self.assertEqual(response.status_code, 200, response.text)
            response = self.client.get(item_url, params={"f": "json"}, verify=False)
            self.assertEqual(
                response.json()["properties"]["details"], "Updated by test"
            )
            self.assertEqual(response.json()["properties"]["state"], "CLOSED")
        finally:
            # Delete
            response = self.client.delete(item_url, verify=False)
            self.assertIn(response.status_code, (200, 204), response.text)

        response = self.client.get(item_url, params={"f": "json"}, verify=False)
        self.assertEqual(response.status_code, 404)


class TestGMFQGISServer(QGISServicesTests, TestCase):
    """
    QGIS Server with the GeoMapFish plugin, behind the geoportal mapserv_proxy
    """

    target = "gmf"


class TestBareQGISServer(QGISServicesTests, TestCase):
    """
    QGIS Server without the GeoMapFish plugin
    """

    target = "bare"
